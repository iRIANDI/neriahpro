    /**
     * Download Project Scaffold & Boilerplate ZIP Archive.
     */
    public function exportScaffold(Request $request, string $slug)
    {
        $blueprint = VisionBlueprint::where('slug', $slug)->firstOrFail();
        $this->authorizeBlueprintAccess($blueprint);

        $gateService = app(\App\Services\Entitlement\BlueprintEntitlementGateService::class);
        $tier = $gateService->resolveUserTier(Auth::user(), $blueprint->slug);

        if (! $gateService->isArtifactEntitled($tier, 'scaffold_zip')) {
            abort(403, 'Akses Ditolak: Unduhan arsip ZIP Starter Kit Scaffold (25+ berkas) eksklusif untuk lisensi Retail Pro / Ultimate atau Proyek Mitra Turnkey. Pada paket Spark Free, Anda dapat meninjau pratinjau arsitektur & DDL 2 tabel utama.');
        }

        try {
            $rawFolder = (string) $request->query('folder', '');
            $customFolder = preg_replace('/[^a-z0-9_-]/', '', strtolower(str_replace(' ', '-', $rawFolder)));
            $customFolder = trim($customFolder, '-_');

            $effectiveSlug = !empty($customFolder) 
                ? $customFolder 
                : ScaffoldGeneratorService::deriveShortSlug($blueprint->slug ?: 'project', $blueprint);

            $downloadFilename = $effectiveSlug . '.zip';

            // Check if pre-generated by background job
            $existingZip = $blueprint->user_metadata['scaffold_zip_path'] ?? null;
            $savedSlug = $blueprint->user_metadata['short_slug'] ?? null;
            if (empty($customFolder) && $existingZip && file_exists($existingZip) && is_readable($existingZip)) {
                return response()->download($existingZip, $downloadFilename);
            }
            if (!empty($customFolder) && $savedSlug === $customFolder && $existingZip && file_exists($existingZip) && is_readable($existingZip)) {
                return response()->download($existingZip, $downloadFilename);
            }

            $zipPath = ScaffoldGeneratorService::createZipArchive($blueprint, $customFolder ?: null);

            // Update user metadata with ready status and path
            $uMeta = $blueprint->user_metadata ?? [];
            $uMeta['scaffold_ready'] = true;
            if (!empty($customFolder)) {
                $uMeta['short_slug'] = $customFolder;
            }
            $uMeta['scaffold_zip_path'] = $zipPath;
            $uMeta['scaffold_generated_at'] = now()->toIso8601String();
            $blueprint->update(['user_metadata' => $uMeta]);

            return response()->download($zipPath, $downloadFilename);
        } catch (\Throwable $e) {
            \Illuminate\Support\Facades\Log::error('Export scaffold failed: ' . $e->getMessage(), [
                'slug' => $slug,
                'trace' => $e->getTraceAsString(),
            ]);

            if ($request->expectsJson() || $request->isXmlHttpRequest()) {
                return response()->json([
                    'success' => false,
                    'message' => 'Gagal membuat arsip scaffold: ' . $e->getMessage(),
                ], 500);
            }

            return back()->with('error', 'Gagal membuat arsip scaffold: ' . $e->getMessage());
        }
    }

    /**
     * Persist custom workspace / folder name uniquely per blueprint in user_metadata.
     */
    public function saveCustomFolder(Request $request, string $slug): JsonResponse
    {
        $blueprint = VisionBlueprint::where('slug', $slug)->firstOrFail();
        $this->authorizeBlueprintAccess($blueprint);

        $rawFolder = (string) $request->input('folder', '');
        $customFolder = preg_replace('/[^a-z0-9_-]/', '', strtolower(str_replace(' ', '-', $rawFolder)));
        $customFolder = trim($customFolder, '-_');

        $uMeta = $blueprint->user_metadata ?? [];
        if (!empty($customFolder)) {
            $uMeta['short_slug'] = $customFolder;
        } else {
            unset($uMeta['short_slug']);
        }
        // Invalidate previously cached zip path since folder name changed
        unset($uMeta['scaffold_zip_path']);
        $uMeta['scaffold_ready'] = false;
        $blueprint->update(['user_metadata' => $uMeta]);

        $effectiveSlug = !empty($customFolder)
            ? $customFolder
            : ScaffoldGeneratorService::deriveShortSlug($blueprint->slug ?: 'project', $blueprint);

        return response()->json([
            'success' => true,
            'custom_folder' => $customFolder ?: null,
            'effective_slug' => $effectiveSlug,
            'message' => 'Nama folder kerja kustom berhasil disimpan secara unik untuk proyek ini.',
        ]);
    }

    /**
     * Dispatch background job to generate project scaffold and zip archive asynchronously.
     */
    public function generateAsync(Request $request, string $slug): JsonResponse
    {
        $blueprint = VisionBlueprint::where('slug', $slug)->firstOrFail();
        $this->authorizeBlueprintAccess($blueprint);

        $gateService = app(\App\Services\Entitlement\BlueprintEntitlementGateService::class);
        $tier = $gateService->resolveUserTier(Auth::user(), $blueprint->slug);

        if (! $gateService->isArtifactEntitled($tier, 'scaffold_zip')) {
            return response()->json([
                'success' => false,
                'message' => 'Akses Ditolak: Pembuatan arsip ZIP Starter Kit Scaffold eksklusif untuk lisensi Retail Pro / Ultimate atau Proyek Mitra Turnkey.',
            ], 403);
        }

        $rawFolder = (string) $request->input('folder', $request->query('folder', ''));
        $customFolder = preg_replace('/[^a-z0-9_-]/', '', strtolower(str_replace(' ', '-', $rawFolder)));
        $customFolder = trim($customFolder, '-_');
        if (!empty($customFolder)) {
            $uMeta = $blueprint->user_metadata ?? [];
            $uMeta['short_slug'] = $customFolder;
            $blueprint->update(['user_metadata' => $uMeta]);
        }

        $cacheKey = "scaffold_job_status:{$blueprint->slug}";

        // If instant mode requested, execute synchronously immediately
        if ($request->boolean('instant') || $request->has('sync')) {
            \App\Jobs\GenerateBlueprintScaffoldJob::dispatchSync($blueprint->id);
            $cached = Cache::get($cacheKey);
            return response()->json(array_merge([
                'success' => true,
                'status' => 'completed',
                'progress' => 100,
                'message' => 'Paket scaffold 22+ file & Docker compose berhasil dibuat secara instan.',
                'download_url' => route('blueprint.export-scaffold', $blueprint->slug),
            ], is_array($cached) ? $cached : []));
        }

        Cache::put($cacheKey, [
            'status' => 'queued',
            'progress' => 5,
            'message' => 'Job generasi scaffold berhasil dijadwalkan ke antrean server...',
            'updated_at' => now()->toIso8601String(),
        ], now()->addDay());

        // Dispatch after response so the HTTP process finishes it even if no queue daemon is active
        try {
            \App\Jobs\GenerateBlueprintScaffoldJob::dispatchAfterResponse($blueprint->id);
        } catch (\Throwable $e) {
            \App\Jobs\GenerateBlueprintScaffoldJob::dispatch($blueprint->id);
        }

        return response()->json([
            'success' => true,
            'status' => 'queued',
            'message' => 'Pembuatan paket scaffold 22+ file & Docker compose telah dijadwalkan di latar belakang.',
            'job_status_url' => route('blueprint.scaffold.job-status', $blueprint->slug),
        ]);
    }

    /**
     * Check the status and progress of the background scaffold generation job.
     */
    public function getJobStatus(Request $request, string $slug): JsonResponse
    {
        $blueprint = VisionBlueprint::where('slug', $slug)->firstOrFail();
        $this->authorizeBlueprintAccess($blueprint);

        $cacheKey = "scaffold_job_status:{$blueprint->slug}";
        $cached = Cache::get($cacheKey);

        if ($cached && is_array($cached)) {
            // Auto-rescue stalled jobs if queued on server with no queue worker daemon running
            if (($cached['status'] ?? '') === 'queued') {
                $updatedAt = isset($cached['updated_at']) ? \Carbon\Carbon::parse($cached['updated_at']) : null;
                // If queued for >= 2 seconds without pickup, execute inline to prevent hanging
                if (! $updatedAt || now()->diffInSeconds($updatedAt) >= 2) {
                    try {
                        \App\Jobs\GenerateBlueprintScaffoldJob::dispatchSync($blueprint->id);
                        $cached = Cache::get($cacheKey);
                    } catch (\Throwable $e) {
                        \Illuminate\Support\Facades\Log::error('Inline scaffold job execution failed: ' . $e->getMessage());
                    }
                }
            }

            return response()->json(array_merge(['success' => true], is_array($cached) ? $cached : []));
        }

        // If not in cache, inspect blueprint metadata
        $uMeta = $blueprint->user_metadata ?? [];
        if (! empty($uMeta['scaffold_ready']) && ! empty($uMeta['scaffold_zip_path']) && file_exists($uMeta['scaffold_zip_path'])) {
            return response()->json([
                'success' => true,
                'status' => 'completed',
                'progress' => 100,
                'message' => 'Scaffold starter kit sudah tersedia.',
                'file_count' => $uMeta['scaffold_file_count'] ?? 22,
                'generated_at' => $uMeta['scaffold_generated_at'] ?? null,
                'download_url' => route('blueprint.export-scaffold', $blueprint->slug),
            ]);
        }

        return response()->json([
            'success' => true,
            'status' => 'idle',
            'progress' => 0,
            'message' => 'Belum ada proses background job scaffold yang berjalan.',
            'download_url' => route('blueprint.export-scaffold', $blueprint->slug),
        ]);
    }

    /**
     * Preview Project Scaffold Files in JSON format for in-browser viewer.
     */
    public function previewScaffold(Request $request, string $slug): JsonResponse
    {
        $blueprint = VisionBlueprint::where('slug', $slug)->firstOrFail();
        $this->authorizeBlueprintAccess($blueprint);

        $gateService = app(\App\Services\Entitlement\BlueprintEntitlementGateService::class);
        $tier = $gateService->resolveUserTier(Auth::user(), $blueprint->slug);

        try {
            $rawFolder = (string) $request->query('folder', '');
            $customFolder = preg_replace('/[^a-z0-9_-]/', '', strtolower(str_replace(' ', '-', $rawFolder)));
            $customFolder = trim($customFolder, '-_');

            $files = ScaffoldGeneratorService::generateFiles($blueprint, $customFolder ?: null);
            $customizations = $blueprint->user_metadata['scaffold_customizations'] ?? [];

            // Auto-clean any corrupted customization placeholders in database
            $cleanedCustom = [];
            $needsMetaClean = false;
            foreach ($customizations as $cKey => $cVal) {
                $trimmed = is_string($cVal) ? trim($cVal) : '';
                if ($trimmed === '' || $trimmed === 'Memuat berkas...' || str_starts_with($trimmed, '// Berkas ') || str_starts_with($trimmed, '// Memuat berkas')) {
                    $needsMetaClean = true;
                    continue;
                }
                $cleanedCustom[$cKey] = $cVal;
            }

            if ($needsMetaClean) {
                $uMeta = $blueprint->user_metadata ?? [];
                $uMeta['scaffold_customizations'] = $cleanedCustom;
                $blueprint->update(['user_metadata' => $uMeta]);
                $customizations = $cleanedCustom;
            }

            // Guaranteed presence of all 22 required preview tabs
            $requiredTabs = [
                'docs/product/PRODUCT-BRIEF.md' => fn() => ScaffoldGeneratorService::generateProductBrief($blueprint),
                'docs/architecture/ADR-001-postgresql-ulid.md' => fn() => ScaffoldGeneratorService::generateAdr001($blueprint),
                'docs/adr/ADR-001-architectural-paradigm.md' => fn() => ScaffoldGeneratorService::generateAdr001($blueprint),
                'docker-compose.yml' => fn() => ScaffoldGeneratorService::generateDockerCompose($blueprint, $blueprint->slug ?: 'app'),
                'openapi.json' => fn() => ScaffoldGeneratorService::generateOpenApiSpec($blueprint, []),
                'schema_complete.sql' => fn() => ScaffoldGeneratorService::generateDatabaseMigrationsSql($blueprint, []),
                'database/migrations/schema_complete.sql' => fn() => ScaffoldGeneratorService::generateDatabaseMigrationsSql($blueprint, []),
                'design/wireframes/screens.md' => fn() => ScaffoldGeneratorService::generateWireframeBlueprints($blueprint, []),
                'design/tokens.json' => fn() => ScaffoldGeneratorService::generateDesignTokens($blueprint),
                'routes/web.php' => fn() => ScaffoldGeneratorService::generateLaravelRoutes($blueprint, []),
                'routes/api.php' => fn() => ScaffoldGeneratorService::generateLaravelApiRoutes($blueprint, []),
                'app/Http/Controllers/HealthProbeController.php' => fn() => ScaffoldGeneratorService::generateHealthProbeController($blueprint->slug ?: 'app'),
                'app/api/route.ts' => fn() => ScaffoldGeneratorService::generateNextJsRoute($blueprint, []),
                'database/seeders/SyntheticDataSeeder.php' => fn() => ScaffoldGeneratorService::generateSyntheticDataSeeder($blueprint, []),
                '.cursorrules' => fn() => PrdGeneratorService::toCursorrules($blueprint, $blueprint->prd_content ?? []),
                'AGENTS.md' => fn() => PrdGeneratorService::toCursorrules($blueprint, $blueprint->prd_content ?? []),
                'tests/Feature/ApiContractTest.php' => fn() => ScaffoldGeneratorService::generateContractTest($blueprint, []),
                'tests/e2e/smoke.spec.ts' => fn() => ScaffoldGeneratorService::generatePlaywrightE2ETest($blueprint, []),
                'tests/e2e/critical-flows.spec.ts' => fn() => ScaffoldGeneratorService::generatePlaywrightE2ETest($blueprint, []),
                'deploy.sh' => fn() => ScaffoldGeneratorService::generateDeployScript($blueprint, $blueprint->slug ?: 'app'),
                '.github/workflows/deploy.yml' => fn() => ScaffoldGeneratorService::generateCiCdWorkflow($blueprint, $blueprint->slug ?: 'app'),
                'scripts/backup.sh' => fn() => ScaffoldGeneratorService::generateBackupScript($blueprint, $blueprint->slug ?: 'app'),
                'scripts/restore.sh' => fn() => ScaffoldGeneratorService::generateRestoreScript($blueprint, $blueprint->slug ?: 'app'),
                'docs/runbooks/disaster-recovery.md' => fn() => ScaffoldGeneratorService::generateDisasterRecoveryRunbook($blueprint, $blueprint->slug ?: 'app'),
                'docs/disaster-recovery-runbook.md' => fn() => ScaffoldGeneratorService::generateDisasterRecoveryRunbook($blueprint, $blueprint->slug ?: 'app'),
                'README.md' => fn() => ScaffoldGeneratorService::generateReadme($blueprint, $blueprint->nama_bisnis ?: 'Proyek', $blueprint->slug ?: 'app'),
